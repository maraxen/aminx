"""Regenerate the aminx FAMPNN reference-conformer table from the real upstream module.

Imports ``fampnn.data.life`` (``RESTYPE_REF_POS_ATOM37``: CA-centred CCD template coordinates, built
at import time in float32) and rewrites the ``_REF_POS_ATOM37_LIST`` block of
``src/aminx/families/fampnn/constants.py`` for the 20 amino acids. Row 20 (UNK) is not reproducible
upstream (an unseeded RDKit embed, ``life.py:419-424``), so it is left as is.

Run in the oracle environment (torch, rdkit, gemmi on the path; see launch_fampnn_oracle.sh):
  PYTHONPATH=<stubs>:<extra> python scripts/parity/regen_fampnn_ref_pos.py \
      --fampnn-root ~/repos/fampnn --constants src/aminx/families/fampnn/constants.py
"""

from __future__ import annotations

import argparse
import logging
import re
import sys
from pathlib import Path

import numpy as np

LOG = logging.getLogger("regen_fampnn_ref_pos")
RESTYPE_NAMES = "ALA ARG ASN ASP CYS GLN GLU GLY HIS ILE LEU LYS MET PHE PRO SER THR TRP TYR VAL".split()


def _fmt(x: float) -> str:
  s = np.format_float_positional(np.float32(x), unique=True, trim="-")
  return "0" if s in ("0", "-0") else s


def main() -> int:
  ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
  ap.add_argument("--fampnn-root", required=True)
  ap.add_argument("--constants", required=True, type=Path)
  ap.add_argument("--dry-run", action="store_true")
  args = ap.parse_args()
  logging.basicConfig(level=logging.INFO, format="%(message)s")
  sys.dont_write_bytecode = True
  sys.path.insert(0, args.fampnn_root)
  from fampnn.data import life

  table = life.RESTYPE_REF_POS_ATOM37.numpy()
  assert table.shape == (21, 37, 3)
  text = args.constants.read_text()
  for i, name in enumerate(RESTYPE_NAMES):
    start = text.index(f"  # {i}: {name}\n  [\n", text.index("_REF_POS_ATOM37_LIST"))
    end = text.index("\n  ],\n", start) + len("\n  ],\n")
    rows = "\n".join(f"    [{_fmt(a)}, {_fmt(b)}, {_fmt(c)}]," for a, b, c in table[i])
    block = f"  # {i}: {name}\n  [\n{rows}\n  ],\n"
    text = text[:start] + block + text[end:]
  text = re.sub(
    r"# CA-centered CCD model coordinates.*?\n_REF_POS_ATOM37_LIST",
    "# CA-centered CCD template coordinates, regenerated by scripts/parity/regen_fampnn_ref_pos.py from the real\n"
    "# upstream table ``fampnn.data.life.RESTYPE_REF_POS_ATOM37`` (float32 values, rows 0-19). Row 20 (UNK) has no CCD\n"
    "# template upstream (an unseeded RDKit embed, ``life.py:419-424``, different in every process); its present\n"
    "# atoms are N, CA, C and O taken from the alanine template. The checkpoint does not store this table.\n"
    "_REF_POS_ATOM37_LIST",
    text,
    count=1,
    flags=re.S,
  )
  if not args.dry_run:
    args.constants.write_text(text)
  LOG.info("rewrote 20 rows (dry_run=%s)", args.dry_run)
  return 0


if __name__ == "__main__":
  raise SystemExit(main())
